#include "huma/docgen.hpp"
#include <sstream>

namespace huma {

std::string DocGenerator::generateMarkdown(Program& program, const std::string& project_name) {
    std::ostringstream ss;
    ss << "# " << project_name << " — HUMA X API Documentation\n\n";
    ss << "Generated by HUMA X Documentation Tool.\n\n";

    std::vector<FuncDeclStmt*> functions;
    std::vector<ClassDeclStmt*> classes;
    std::vector<VarDeclStmt*> globals;

    for (auto& s : program.statements) {
        if (auto* fn = dynamic_cast<FuncDeclStmt*>(s.get())) {
            functions.push_back(fn);
        } else if (auto* cls = dynamic_cast<ClassDeclStmt*>(s.get())) {
            classes.push_back(cls);
        } else if (auto* var = dynamic_cast<VarDeclStmt*>(s.get())) {
            globals.push_back(var);
        }
    }

    if (!functions.empty()) {
        ss << "## Functions\n\n";
        for (auto* fn : functions) {
            ss << "### `call " << fn->name;
            if (!fn->params.empty()) {
                ss << " using ";
                for (size_t i = 0; i < fn->params.size(); ++i) {
                    if (i > 0) ss << ", ";
                    ss << fn->params[i];
                }
            }
            ss << "`\n\n";
            ss << "- **Defined at**: Line " << fn->loc.line << "\n";
            ss << "- **Parameters**: " << fn->params.size() << "\n\n";
        }
    }

    if (!classes.empty()) {
        ss << "## Classes\n\n";
        for (auto* cls : classes) {
            ss << "### `class " << cls->name << "`\n\n";
            ss << "- **Fields**: ";
            if (cls->fields.empty()) ss << "None\n";
            else {
                for (size_t i = 0; i < cls->fields.size(); ++i) {
                    if (i > 0) ss << ", ";
                    ss << "`" << cls->fields[i] << "`";
                }
                ss << "\n";
            }
            ss << "- **Methods**:\n";
            for (auto& m : cls->methods) {
                ss << "  - `" << m->name << "`: " << m->params.size() << " parameters\n";
            }
            ss << "\n";
        }
    }

    if (!globals.empty()) {
        ss << "## Global Variables & Constants\n\n";
        for (auto* var : globals) {
            ss << "- `" << (var->is_fixed ? "fixed " : "make ") << var->name << "` (Line " << var->loc.line << ")\n";
        }
    }

    return ss.str();
}

std::string DocGenerator::generateHtml(Program& program, const std::string& project_name) {
    std::string md = generateMarkdown(program, project_name);
    std::ostringstream ss;
    ss << "<!DOCTYPE html>\n<html>\n<head>\n  <meta charset=\"utf-8\">\n";
    ss << "  <title>" << project_name << " Documentation</title>\n";
    ss << "  <style>body { font-family: system-ui, sans-serif; line-height: 1.6; max-width: 800px; margin: 40px auto; padding: 0 20px; color: #222; } pre { background: #f4f4f5; padding: 12px; border-radius: 6px; } code { color: #0284c7; }</style>\n";
    ss << "</head>\n<body>\n";
    ss << "<pre>" << md << "</pre>\n";
    ss << "</body>\n</html>\n";
    return ss.str();
}

} // namespace huma
